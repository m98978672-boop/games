"""Private real-model repair test against live Steam; never renders or uploads.

The first two deliberately bad plans are synthetic; rating is a fixture, not a
model opinion or a publishable review. The actual correction is generated by Qwen.
"""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import game_reviews
from steam_catalog import load_steam_games

games = load_steam_games(limit=3)
game = games[0]
gid = str(game['id'])
fixture = json.dumps({'schema_version':1, 'game_id':gid,
    'selected_feature_ids':[f'{gid}-f1', f'{gid}-f2'], 'minus_feature_id':f'{gid}-f1',
    'possible_minus':'Неизвестно', 'idea_score':7, 'hook':'Что предлагает эта игра?'}, ensure_ascii=False)
real_generate = game_reviews.generate_with_qwen
calls = []
def inject_failure(messages, **kwargs):
    calls.append(1)
    return fixture if len(calls) <= 2 else real_generate(messages, **kwargs)
game_reviews.generate_with_qwen = inject_failure
review = game_reviews.generate_game_review(games)
assert len(calls) >= 3 and review['game_id'] == gid and review['idea_score'] == 7
print(json.dumps({'fixture_only':True,'uploaded':False,'calls':len(calls),'game_id':gid,
                  'possible_minus':review['possible_minus'],'minus_evidence':review['minus_evidence'],
                  'limitation_generation':review.get('limitation_generation','model')},ensure_ascii=False))
# Also test the real end-to-end plan. This is private metadata, not a video or upload.
game_reviews.generate_with_qwen = real_generate
real = game_reviews.generate_game_review(games)
print(json.dumps({'fixture_only':False, 'uploaded':False, 'game_id':real['game_id'],
                  'possible_minus':real['possible_minus'], 'minus_evidence':real['minus_evidence'],
                  'limitation_generation':real.get('limitation_generation','model')},ensure_ascii=False))
# Force corrupt JSON, but obtain the replacement score from the real model.
malformed_calls=[]
def inject_bad_json(messages, **kwargs):
    malformed_calls.append(1)
    return '{broken' if len(malformed_calls) <= 2 else real_generate(messages, **kwargs)
game_reviews.generate_with_qwen = inject_bad_json
recovered = game_reviews.generate_game_review(games)
assert recovered['selection_method'] == 'first_eligible_catalog_candidate_after_invalid_json'
assert type(recovered['idea_score']) in (int, float) and 1 <= recovered['idea_score'] <= 10
print(json.dumps({'malformed_fixture_only':True, 'uploaded':False,
                  'score_from_model':recovered['idea_score'], 'game_id':recovered['game_id']},ensure_ascii=False))
