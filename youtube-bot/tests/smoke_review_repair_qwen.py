"""Private real-model repair test against live Steam; never renders or uploads.

The first two deliberately bad plans are synthetic; rating is a fixture, not a
model opinion or a publishable review. The actual correction is generated by Qwen.
"""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import game_reviews
from steam_catalog import load_steam_games

games = load_steam_games(limit=3)
game = games[0]
gid = str(game['id'])
fixture = json.dumps({'schema_version':1, 'game_id':gid,
    'selected_feature_ids':[f'{gid}-f1', f'{gid}-f2'], 'minus_feature_id':f'{gid}-f1',
    'possible_minus':'Неизвестно', 'idea_score':7, 'hook':'Что предлагает эта игра?'}, ensure_ascii=False)
real_generate = game_reviews.generate_with_qwen
calls = []
def inject_failure(messages, **kwargs):
    calls.append(1)
    return fixture if len(calls) <= 2 else real_generate(messages, **kwargs)
game_reviews.generate_with_qwen = inject_failure
review = game_reviews.generate_game_review(games)
assert len(calls) >= 3 and review['game_id'] == gid and review['idea_score'] == 7
print(json.dumps({'fixture_only':True,'uploaded':False,'calls':len(calls),'game_id':gid,
                  'possible_minus':review['possible_minus'],'minus_evidence':review['minus_evidence'],
                  'limitation_generation':review.get('limitation_generation','model')},ensure_ascii=False))
