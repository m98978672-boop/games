#!/usr/bin/env python3
"""Resumable mixed-task 15h research trainer, not a production game AI.

Training time counts only forward/backward/optimizer work. Checkpoints include
LoRA, best-dev adapter, optimizer, RNG, dataset hash and active time. Only
trusted archives generated by this workflow should ever be loaded.
"""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import random
import shutil
import subprocess
import tarfile
import time
import torch
import torch.nn.functional as F
from peft import PeftModel
from transformers import AutoModelForImageTextToText,AutoTokenizer
from huggingface_hub import hf_hub_download

spec=importlib.util.spec_from_file_location('helpers',Path(__file__).with_name('train-qwen.py'))
helper=importlib.util.module_from_spec(spec);spec.loader.exec_module(helper)
BASE_SHA='04b1c301231dd422b8860db31311ab2721511346a32cb1e079c4c4e5f1fe4696'

def read_data(folder):
    wm=json.loads((folder/'waypoint/manifest.json').read_text())
    if wm['schema']!='frontline-obstacle-game-v2': raise ValueError('wrong waypoint schema')
    route={}
    for split in ('train','dev','test'):
        for suffix in ('','-all'):
            name=split+suffix; raw=(folder/'waypoint'/f'{name}.jsonl').read_bytes()
            field='allSha256' if suffix else 'sha256'
            if hashlib.sha256(raw).hexdigest()!=wm['counts'][split][field]:raise ValueError('waypoint hash mismatch')
            route[name]=[json.loads(x) for x in raw.splitlines()]
        if len(route[split])!=wm['counts'][split]['kept'] or len(route[split+'-all'])!=wm['counts'][split]['generated']:raise ValueError('wrong waypoint count')
        if any(r['response'] not in ('U','D') for r in route[split]):raise ValueError('bad waypoint label')
    for a,b in [('train','dev'),('train','test'),('dev','test')]:
        keys=lambda split:{json.dumps(r['input'],sort_keys=True) for r in route[split+'-all']}
        seeds=lambda split:{r['spec']['seed'] for r in route[split+'-all']}
        sizes=lambda split:{(r['spec']['width'],r['spec']['height']) for r in route[split+'-all']}
        if keys(a)&keys(b) or seeds(a)&seeds(b) or sizes(a)&sizes(b):raise ValueError('waypoint leakage')
    cm,commander=helper.read_data(folder/'commander')
    tm=json.loads((folder/'commander/test-manifest.json').read_text())
    raw=(folder/'commander/test.jsonl').read_bytes()
    if hashlib.sha256(raw).hexdigest()!=tm['sha256']:raise ValueError('commander test hash mismatch')
    test=[json.loads(x) for x in raw.splitlines()]
    if len(test)!=tm['count'] or set(tm['seeds']) & (set(cm['trainSeeds']) | set(cm['evalSeeds'])):raise ValueError('commander test seed leakage')
    previous={json.dumps(r['input'],sort_keys=True) for s in ('train','eval') for r in commander[s]}
    if any(r['seed'] not in tm['seeds'] or json.dumps(r['input'],sort_keys=True) in previous for r in test):raise ValueError('commander test observation leakage')
    files=sorted(p for p in folder.rglob('*') if p.is_file())
    d=hashlib.sha256()
    for p in files:
        rel=str(p.relative_to(folder)).encode();d.update(len(rel).to_bytes(4,'big'));d.update(rel)
        raw=p.read_bytes();d.update(len(raw).to_bytes(8,'big'));d.update(raw)
    return wm,route,cm,commander,d.hexdigest()

def command_samples(rows,maximum=6):
    pools={a:[r for r in rows if json.loads(r['response'])['action']==a] for a in ('hold','build','supply','none')}
    selected=[]
    while len(selected)<maximum:
        added=False
        for values in pools.values():
            if values:
                used={r['seed'] for r in selected};i=next((i for i,r in enumerate(values) if r['seed'] not in used),0)
                selected.append(values.pop(i));added=True
                if len(selected)>=maximum:break
        if not added:break
    return selected

def main():
    p=argparse.ArgumentParser();p.add_argument('--data',type=Path,required=True);p.add_argument('--work',type=Path,required=True)
    p.add_argument('--initial-adapter',type=Path);p.add_argument('--resume',type=Path)
    p.add_argument('--active-seconds',type=float,required=True);p.add_argument('--phase',type=int,required=True)
    p.add_argument('--checkpoint-every',type=float,default=900);p.add_argument('--eval-every',type=float,default=2700)
    p.add_argument('--release');p.add_argument('--max-steps',type=int,default=0);p.add_argument('--eval-commands',type=int,default=6);p.add_argument('--eval-token-budget',type=int,default=48);args=p.parse_args()
    if not (0<args.active_seconds<=18000) or args.phase not in (1,2,3) or args.checkpoint_every<=0 or args.eval_every<=0 or not 1<=args.eval_commands<=6 or not 1<=args.eval_token_budget<=96:raise ValueError('bad schedule')
    if (args.initial_adapter is None)==(args.resume is None):raise ValueError('provide initial adapter OR resume')
    torch.set_num_threads(int(os.getenv('OMP_NUM_THREADS','2')));torch.manual_seed(97531);random.seed(97531)
    wm,nav,cm,commander,datahash=read_data(args.data)
    weights=hf_hub_download(helper.MODEL,'model.safetensors-00001-of-00001.safetensors',revision=helper.REVISION)
    digest=hashlib.sha256()
    with open(weights,'rb') as f:
        for b in iter(lambda:f.read(4*1024*1024),b''):digest.update(b)
    if digest.hexdigest()!=BASE_SHA:raise ValueError('base model hash mismatch')
    tok=AutoTokenizer.from_pretrained(helper.MODEL,revision=helper.REVISION)
    ids={c:tok.encode(c,add_special_tokens=False) for c in ('U','D')}
    if any(len(v)!=1 for v in ids.values()) or ids['U']==ids['D']:raise ValueError('unexpected waypoint tokenization')
    ids={k:v[0] for k,v in ids.items()}
    def encode_route(row):
        prefix,target=helper.encode(tok,wm['system'],{'input':row['input'],'response':row['response']})
        if target[0]!=ids[row['response']]:raise ValueError('unexpected waypoint target')
        return prefix,ids[row['response']]
    def augment(row):
        # Equivalent geometry only: reorder segments and optionally swap their endpoints.
        inp=dict(row['input']);walls=[list(s) for s in inp['walls']];random.shuffle(walls)
        inp['walls']=[([w[2],w[3],w[0],w[1]] if random.random()<.5 else w) for w in walls]
        return {'input':inp,'response':row['response']}
    comm_train=[helper.encode(tok,cm['prompt'],r) for r in commander['train']]
    comm_eval=[(helper.encode(tok,cm['prompt'],r),r) for r in command_samples(commander['eval'],args.eval_commands)]
    route_eval=[encode_route(r) for r in nav['dev']]
    if not (comm_train and comm_eval and route_eval and nav['train']):raise ValueError('empty training/evaluation data')
    base=AutoModelForImageTextToText.from_pretrained(helper.MODEL,revision=helper.REVISION,dtype=torch.bfloat16,low_cpu_mem_usage=True)
    adapter=args.initial_adapter if args.initial_adapter else args.resume/'adapter'
    model=PeftModel.from_pretrained(base,adapter,is_trainable=True)
    model.gradient_checkpointing_enable(gradient_checkpointing_kwargs={'use_reentrant':False})
    trainable=[x for x in model.parameters() if x.requires_grad]
    if not trainable:raise ValueError('no trainable weights')
    opt=torch.optim.AdamW(trainable,lr=3e-5)
    args.work.mkdir(parents=True,exist_ok=True);best_dir=args.work/'best'
    active=0.0;step=0;best_score=None;best_metrics=None;phase_start=0.0;slot=0;task_counts={'waypoint':0,'commander':0}
    if args.resume:
        progress=json.loads((args.resume/'progress.json').read_text())
        if progress['dataset_sha256']!=datahash or progress['phase'] not in (args.phase-1,args.phase) or progress['eval_commands']!=args.eval_commands or progress['eval_token_budget']!=args.eval_token_budget:raise ValueError('wrong dataset, evaluation settings or phase')
        active=float(progress['active_seconds']);step=int(progress['steps']);best_score=tuple(progress['best_score']);best_metrics=progress['best_metrics'];task_counts=dict(progress['task_counts'])
        if progress['phase']==args.phase:
            if float(progress['phase_budget_seconds'])!=args.active_seconds:raise ValueError('cannot change budget when resuming a phase')
            phase_start=float(progress['phase_start_active']);slot=int(progress.get('next_slot',0))
        else:
            if not args.max_steps and active<float(progress['phase_start_active'])+float(progress['phase_budget_seconds']):raise ValueError('previous phase did not finish')
            phase_start=active
        state=torch.load(args.resume/'state.pt',map_location='cpu',weights_only=True)
        opt.load_state_dict(state['optimizer']);torch.set_rng_state(state['torch_rng']);random.setstate(state['python_rng'])
        if best_dir.exists():shutil.rmtree(best_dir)
        shutil.copytree(args.resume/'best',best_dir)
        print('resumed',json.dumps({'phase':args.phase,'steps':step,'active_seconds':active,'phase_start_active':phase_start,'best':best_metrics}),flush=True)
    def route_logits(prefix):return model(input_ids=torch.tensor([prefix]),use_cache=False,logits_to_keep=1).logits[0,-1].float()
    def evaluate():
        model.eval();correct=0
        with torch.no_grad():
            for prefix,target in route_eval:
                l=route_logits(prefix);pred=max(('U','D'),key=lambda c:float(l[ids[c]]));correct+=int(ids[pred]==target)
            exact=0;valid=0
            for (prefix,_),row in comm_eval:
                inp=torch.tensor([prefix]);out=model.generate(input_ids=inp,do_sample=False,max_new_tokens=args.eval_token_budget,use_cache=True,pad_token_id=tok.pad_token_id)
                raw=tok.decode(out[0,len(prefix):],skip_special_tokens=True,clean_up_tokenization_spaces=False).strip()
                try:
                    obj=json.loads(raw);expected=json.loads(row['response']);valid+=int(isinstance(obj,dict));exact+=int(obj==expected)
                except (ValueError,TypeError):pass
        metrics={'waypoint_correct':correct,'waypoint_total':len(route_eval),'commander_exact':exact,'commander_json':valid,'commander_total':len(comm_eval)}
        model.train();return metrics
    def update_best():
        nonlocal best_score,best_metrics
        metrics=evaluate();score=(metrics['waypoint_correct'],metrics['commander_exact'])
        if best_score is None or score>best_score:
            model.save_pretrained(best_dir,safe_serialization=True);best_score=score;best_metrics=metrics
        print('validation',json.dumps({'phase':args.phase,'step':step,'active_seconds':active,'current':metrics,'best':best_metrics}),flush=True)
    def checkpoint(final=False,slot=0):
        # Construct the snapshot completely before replacing a local checkpoint.
        temp=args.work/'snapshot-tmp';live=args.work/'snapshot'
        if temp.exists():shutil.rmtree(temp)
        temp.mkdir();model.save_pretrained(temp/'adapter',safe_serialization=True);shutil.copytree(best_dir,temp/'best')
        torch.save({'optimizer':opt.state_dict(),'torch_rng':torch.get_rng_state(),'python_rng':random.getstate()},temp/'state.pt')
        progress={'schema':'frontline-long-checkpoint-v1','phase':args.phase,'steps':step,'active_seconds':active,'phase_start_active':phase_start,'phase_budget_seconds':args.active_seconds,'next_slot':1-slot,'task_counts':task_counts,'eval_commands':args.eval_commands,'eval_token_budget':args.eval_token_budget,'dataset_sha256':datahash,'best_score':list(best_score),'best_metrics':best_metrics,'initial_adapter_release':'frontline-obstacle-v2-44626512571','model':helper.MODEL,'revision':helper.REVISION}
        (temp/'progress.json').write_text(json.dumps(progress,ensure_ascii=False,indent=2)+'\n')
        old=args.work/'snapshot-old'
        if old.exists():shutil.rmtree(old)
        if live.exists():live.rename(old)
        temp.rename(live)
        if old.exists():shutil.rmtree(old)
        name=f'phase-{args.phase}-complete.tar.gz' if final else f'phase-{args.phase}-slot-{slot}.tar.gz'
        archive=args.work/name
        with tarfile.open(archive,'w:gz') as t:t.add(live,arcname='checkpoint')
        if args.release:
            if not os.getenv('GH_TOKEN'):raise RuntimeError('release checkpoint requested without GH_TOKEN')
            # Alternating slots retain at least one prior remote checkpoint if an upload fails.
            for attempt in range(3):
                result=subprocess.run(['gh','release','upload',args.release,str(archive),'--clobber'],check=False)
                if result.returncode==0:break
                if attempt==2:raise RuntimeError('checkpoint upload failed')
                time.sleep(10*(attempt+1))
        print('checkpoint',json.dumps({'phase':args.phase,'step':step,'active_seconds':active,'file':name,'uploaded':bool(args.release),'complete':final}),flush=True)
    if best_score is None:update_best()
    goal=phase_start+args.active_seconds;next_ckpt=active+args.checkpoint_every;next_eval=active+args.eval_every;initial_step=step
    checkpoint(slot=slot);slot=1-slot;model.train()
    while active<goal and (not args.max_steps or step-initial_step<args.max_steps):
        # 25% imitation of isolated strategic snapshots, 75% waypoint decisions.
        if random.random()<.25:
            prefix,target=random.choice(comm_train);kind='commander'
            start=time.monotonic();opt.zero_grad(set_to_none=True);loss=helper.example_loss(model,(prefix,target))
        else:
            row=augment(random.choice(nav['train']));prefix,target=encode_route(row);kind='waypoint'
            start=time.monotonic();opt.zero_grad(set_to_none=True);loss=F.cross_entropy(route_logits(prefix).unsqueeze(0),torch.tensor([target]))
        if not torch.isfinite(loss):raise ValueError('non-finite loss')
        loss.backward();torch.nn.utils.clip_grad_norm_(trainable,1.0);opt.step();active+=time.monotonic()-start;step+=1;task_counts[kind]+=1
        if step%20==0:print('training',json.dumps({'phase':args.phase,'step':step,'active_seconds':round(active,2),'kind':kind,'loss':float(loss.detach())}),flush=True)
        if active>=next_eval:update_best();next_eval=active+args.eval_every
        if active>=next_ckpt:checkpoint(slot=slot);slot=1-slot;next_ckpt=active+args.checkpoint_every
    if not args.max_steps and active<goal:raise RuntimeError('phase ended before reaching requested training time')
    update_best();checkpoint(final=True)
    print('phase complete',json.dumps({'phase':args.phase,'steps':step,'active_seconds':active,'requested_additional_seconds':args.active_seconds,'best':best_metrics}),flush=True)
if __name__=='__main__':main()
