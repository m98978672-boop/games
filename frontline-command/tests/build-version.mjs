import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { BUILD_VERSION, mountBuildVersion } from '../src/core/build-info.js';
import { inspectGame, formatInspectorReport } from '../src/inspector.js';
import { loadConfig } from '../src/core/config.js';
import { readFile } from 'node:fs/promises';
const cfg=await loadConfig(),pkg=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'));
assert.equal(cfg.flag('build_version_badge_v1',true),false,'new feature defaults off');
assert.ok(BUILD_VERSION.startsWith(pkg.version+'-dev.'),'local build label corresponds to package version, but is not a release');
const dom=new JSDOM('<!doctype html><body><main>menu</main></body>');
const doc=dom.window.document, before=doc.body.innerHTML;
assert.equal(mountBuildVersion(doc,false),null);assert.equal(doc.body.innerHTML,before,'off adds no nodes');
const off=inspectGame(),textOff=formatInspectorReport(off);
assert.ok(!Object.hasOwn(off,'buildVersion'));assert.ok(!textOff.includes('Сборка:'),'off preserves report shape');
const badge=mountBuildVersion(doc,true);assert.equal(badge.textContent,`Сборка ${BUILD_VERSION}`);
const on=inspectGame({buildVersion:BUILD_VERSION});assert.equal(on.buildVersion,BUILD_VERSION);
assert.match(formatInspectorReport(on),new RegExp(BUILD_VERSION.replaceAll('.','\\.')));
badge.remove();assert.equal(doc.body.innerHTML,before,'undo removes the badge');
assert.equal(formatInspectorReport(inspectGame()),textOff,'off restores report output');
console.log('build version: default off, no DOM/report change; on shows the local build in badge and inspector');
