import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const tool=fileURLToPath(new URL('../tools/block0-process-repeatability.mjs',import.meta.url));
const run=(...args)=>spawnSync(process.execPath,[tool,'--seeds=1','--ticks=3',...args],{encoding:'utf8',timeout:30000,maxBuffer:1024*1024});
const normal=run();
assert.equal(normal.status,0,normal.stderr||normal.error?.message);
const ok=JSON.parse(normal.stdout);
assert.equal(ok.passed,true);
assert.equal(ok.runs[0].compared,4);
assert.equal(ok.runs[0].mismatch,null);
assert.match(ok.runs[0].lastSha256,/^[0-9a-f]{64}$/);
const injected=run('--inject-divergence=2');
assert.equal(injected.status,1,injected.stderr||injected.error?.message);
const bad=JSON.parse(injected.stdout);
assert.equal(bad.passed,false);
assert.equal(bad.runs[0].mismatch.tick,2);
assert.notEqual(bad.runs[0].mismatch.sha256A,bad.runs[0].mismatch.sha256B);
const invalid=run('--inject-divergence=4');
assert.notEqual(invalid.status,0);
console.log('Independent processes: exact graph comparison and injected mismatch detected');
