import assert from 'node:assert/strict';
import { createPopulationMonitor } from './acceptance/population-monitor.js';
const run=(target,initial,values)=>{const m=createPopulationMonitor(target,initial);for(const [phase,n] of values)m.observe(n,phase);return m.summary();};
const full=[['start',400],['before-step',400],['after-step',400],['frame',400]];
assert.equal(run(400,400,full).strictExact,true);
assert.equal(run(400,400,full).within2Percent,true);
assert.equal(run(400,400,[['start',400],['frame',400]]).within2Percent,false,'no simulated steps is not evidence');
assert.equal(run(400,400,[...full,['before-step',408],['after-step',408]]).within2Percent,true,'2% boundary included');
const changed=run(400,400,[...full,['before-step',409],['after-step',400]]);
assert.equal(changed.strictExact,false);
assert.equal(changed.within2Percent,false,'transient over 2% between frames must fail');
assert.deepEqual(changed.firstOutside2Percent,{sample:5,phase:'before-step',alive:409});
assert.equal(run(400,399,full).within2Percent,false,'initial count must be exact');
assert.equal(run(400,400,[...full,['before-step',400]]).within2Percent,false,'unpaired step samples are not evidence');
assert.equal(run(500,500,[['start',500],['before-step',490],['after-step',510],['frame',500]]).within2Percent,true);
assert.equal(run(500,500,[['start',500],['before-step',489],['after-step',500],['frame',500]]).within2Percent,false);
const nodeOnly=createPopulationMonitor(400,400,{requireFrames:false});
nodeOnly.observe(400,'start');nodeOnly.observe(400,'before-step');nodeOnly.observe(400,'after-step');
assert.equal(nodeOnly.summary().strictExact,true);
assert.equal(nodeOnly.summary().frameSamples,0);
assert.throws(()=>createPopulationMonitor(400,400,{requireFrames:0}));
assert.throws(()=>createPopulationMonitor(0,0));
assert.throws(()=>createPopulationMonitor(400,400).observe(NaN,'frame'));
assert.throws(()=>createPopulationMonitor(400,400).observe(400,'unknown'));
console.log('Population monitor: exact start, 2% boundary, transient deviations and missing steps checked');
