import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const C = createRequire(import.meta.url)('../src/contracts.js');
const stats = {dropped: 0, ruined: 0};
let s = C.create();
assert(C.accept(s, 'intake', 0, 420, stats).ok);
assert(C.accept(s, 'care', 0, 420, stats).ok);
assert(!C.accept(s, 'load', 0, 420, stats).ok);
assert.equal(C.record(s, stats, 1, 'loaded', {}).length, 0);
assert.equal(C.record(s, stats, 2, 'delivered', {}).length, 0);
let changes = C.record(s, stats, 3, 'delivered', {});
assert.equal(changes[0].id, 'care'); assert.equal(changes[0].reward, 50);
changes = C.record(s, stats, 4, 'delivered', {});
assert.equal(changes[0].id, 'intake'); assert.equal(changes[0].reward, 35);
assert.equal(C.record(s, stats, 5, 'delivered', {}).length, 0);
assert(!C.accept(s, 'intake', 5, 420, stats).ok);
s = C.create(); assert(C.accept(s,'care',0,420,stats).ok);
assert.equal(C.record(s, {dropped:1,ruined:0}, 1, 'delivered', {}).at(0).status,'failed');
assert.equal(s.items[1].progress,0);
s = C.create(); assert(C.accept(s, 'unload', 0, 420, stats).ok);
C.record(s, stats, 1, 'delivered', {source:'rack'});
assert.equal(s.items[2].progress,0);
C.record(s, stats, 2, 'delivered', {source:'truck'});
assert.equal(s.items[2].progress,1);
assert.equal(C.record(s, stats, 3, 'delivered', {source:'truck'})[0].reward,55);
s = C.create(); assert(C.accept(s,'load', 0, 420,stats).ok);
C.record(s,stats,180,'loaded',{}); assert.equal(s.items[3].progress,1);
assert.equal(C.record(s,stats,180,'loaded',{})[0].status,'completed');
s = C.create(); assert(C.accept(s,'load',0,420,stats).ok);
assert.equal(C.record(s,stats,181,'loaded',{})[0].status,'failed');
assert.equal(s.items[3].progress,0);
s = C.create(); assert(C.accept(s,'intake',400,420,stats).ok); assert.equal(s.items[0].deadline,420);
assert.equal(C.finish(s,420)[0].status,'failed');
assert(!C.accept(C.create(),'intake',401,420,stats).ok);
s = C.create(); assert(C.accept(s,'load',0,420,stats).ok); assert(C.cancel(s,'load',1).ok); assert(!C.cancel(s,'load',1).ok); assert(!C.accept(s,'load',2,420,stats).ok);
assert.deepEqual(C.validate(JSON.parse(JSON.stringify(s))),s);
let bad = JSON.parse(JSON.stringify(s)); bad.items[0].id = 'load'; assert.throws(()=>C.validate(bad));
bad = JSON.parse(JSON.stringify(s)); bad.items[0].progress = 999; assert.throws(()=>C.validate(bad));
console.log('✓ Контракты: лимит, события, источники, чистота, сроки, награды, отмена и проверка снимка');
