import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import fs from 'node:fs';
import vm from 'node:vm';
const require = createRequire(import.meta.url);
const dialogue = require('../src/dialogue.js');
function worker(id,x,y) {
  const pos = {x,y};
  return {id, pos, state:{id,name:'Рабочий '+id,pos,state:'idle',dead:false,privacy:false,inToilet:false,orderId:null,carryingId:null,onForklift:false}, body:{collapsed:false,energy:.8}};
}
const a=worker('a',0,0), b=worker('b',1,0), st=dialogue.create(0);
assert.match(dialogue.command(a,'pick',{ok:true}).text,/коробке/);
assert.match(dialogue.command(a,'pick',{ok:true,tech:true}).text,/погрузчик/);
assert.match(dialogue.command(a,'pick',{ok:false,reason:'нет заказов'}).text,/нет заказов/);
assert.equal(dialogue.step(st,[a,b],24,'day',()=>false),null);
const question=dialogue.step(st,[a,b],25,'day',()=>false);
assert.equal(question.workerId,'a'); assert.equal(question.kind,'conversation');
assert.equal(st.pending.listener,'b'); assert.equal(dialogue.step(st,[a,b],27,'day',()=>false),null);
assert.equal(dialogue.step(st,[a,b],27.5,'day',()=>false).workerId,'b');
assert.equal(st.pending,null);
assert.equal(dialogue.step(st,[a,b],30,'day',()=>false),null);
const blocked=dialogue.create(0);
assert.equal(dialogue.step(blocked,[a,b],25,'day',()=>true),null);
assert.equal(blocked.pending,null);
const interrupted=dialogue.create(0);
dialogue.step(interrupted,[a,b],25,'day',()=>false);
b.state.privacy=true;
assert.equal(dialogue.step(interrupted,[a,b],28,'day',()=>false),null);
assert.equal(interrupted.pending,null);
assert.equal(dialogue.command(b,'rest',{ok:true}),null);
b.state.privacy=false;
a.body.energy=.3;
const tired=dialogue.create(0);
assert.match(dialogue.step(tired,[a,b],25,'day',()=>false).text,/Усталость/);
assert(dialogue.event(tired,a,'delivered',30));
assert.equal(dialogue.event(tired,a,'delivered',31),null);
assert(dialogue.event(tired,a,'injury',38));
assert.throws(()=>dialogue.validate({...st,pending:{speaker:'a',listener:'b',topic:'bogus',at:30}}));
assert.deepEqual(dialogue.validate(JSON.parse(JSON.stringify(st))),st);
// Озвучка выключена по умолчанию и использует только локальные русские голоса.
const spoken=[], cancellations=[];
const synth={speaking:false,pending:false,getVoices:()=>[{lang:'ru-RU',localService:false},{lang:'en-US',localService:true}],
  speak:u=>spoken.push(u), cancel:()=>cancellations.push(true)};
const context={window:null,WC:{audio:{isMuted:()=>false}, game:{state:{paused:false,shiftEnded:false}}}};
context.window=context; context.speechSynthesis=synth;
context.SpeechSynthesisUtterance=function(text){this.text=text;};
vm.createContext(context);
vm.runInContext(fs.readFileSync(new URL('../src/voice.js',import.meta.url),'utf8'),context);
const voice=context.WC.voice;
assert.equal(voice.isEnabled(),false); assert.equal(voice.setEnabled(true),false);
assert.equal(voice.speak({workerId:'a',text:'Привет'}),false);
const local={lang:'ru-RU',localService:true,name:'Локальный'};
synth.getVoices=()=>[{lang:'ru-RU',localService:false},local];
assert(voice.setEnabled(true)); assert(voice.speak({workerId:'a',text:'Привет'}));
assert.equal(spoken[0].voice,local); assert.equal(spoken[0].lang,'ru-RU');
synth.speaking=true; assert.equal(voice.speak({workerId:'a',text:'ещё'}),false); synth.speaking=false;
context.WC.audio.isMuted=()=>true; assert.equal(voice.speak({workerId:'a',text:'тишина'}),false);
context.WC.audio.isMuted=()=>false; context.WC.game.state.paused=true;
assert.equal(voice.speak({workerId:'a',text:'пауза'}),false);
assert(voice.setEnabled(false)); assert(cancellations.length>0);
console.log('✓ Реплики: команды, разговоры, прерывания, локальная озвучка, пауза и mute');
