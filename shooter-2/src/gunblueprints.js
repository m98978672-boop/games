  /* ---------------------------------------------------------------------------
     Сборка оружия из чертежа: контуры выдавливаются, тела вращения крутятся
     --------------------------------------------------------------------------- */
  function buildFromBlueprint(id, opts) {
    const T = root.THREE;
    const O = SH2.outline;
    const M = SH2.model;
    const bp = GUNS[id] || GUNS.rifle;
    const o = opts || {};
    const group = new T.Group();
    group.name = 'weapon:' + id;
    (bp.parts || []).forEach((part) => {
      let geo = null;
      if (part.kind === 'outline') {
        geo = O.outlineMesh(part.pts, {
          depth: part.depth, bevel: part.bevel, taper: part.taper,
          bevelSegments: part.bevelSegments || 2
        });
      } else if (part.kind === 'revolve') {
        geo = O.revolve(part.pts, { segments: part.segments || 14 });
        // LatheGeometry строится вокруг Y; поворачиваем под нужную ось
        if (part.axis === 'z') geo.rotateX(Math.PI / 2);
        else if (part.axis === 'x') geo.rotateZ(-Math.PI / 2);
        geo.translate(part.cx || 0, part.cy || 0, part.cz || 0);
      }
      if (!geo) return;
      const mesh = new T.Mesh(geo, M.mat(part.color, { flat: false }));
      mesh.castShadow = !o.noShadow;
      group.add(mesh);
    });
    const muzzle = new T.Object3D();
    muzzle.position.set(bp.muzzle[0], bp.muzzle[1], bp.muzzle[2]);
    group.add(muzzle);
    const grip = new T.Object3D();
    grip.position.set(bp.grip[0], bp.grip[1], bp.grip[2]);
    group.add(grip);
    const fore = new T.Object3D();
    fore.position.set(bp.foregrip[0], bp.foregrip[1], bp.foregrip[2]);
    group.add(fore);
    group.userData = { muzzle, gripPoint: grip, forePoint: fore, sightY: bp.sightY, blueprint: bp };
    return group;
  }

