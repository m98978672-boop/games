for (const u of TRUCKS) u.category = 'trucks';
for (const u of TRAILERS) u.category = 'trailers';
for (const u of CARS) u.category = 'cars';

export function allUnits() {
  return [
    ...TRUCKS.map((u) => ({ ...u, category: 'trucks' })),
    ...TRAILERS.map((u) => ({ ...u, category: 'trailers' })),
    ...CARS.map((u) => ({ ...u, category: 'cars' })),
    ...BUILDINGS.map((u) => ({ ...u, category: 'buildings' })),
  ];
}

export function unitsOf(category) {
  return category === 'trucks' ? TRUCKS
    : category === 'trailers' ? TRAILERS
      : category === 'buildings' ? BUILDINGS
        : CARS;
}

export function findUnit(category, id) {
  const list = unitsOf(category);
  return list.find((u) => u.id === id) || list[0];
}
