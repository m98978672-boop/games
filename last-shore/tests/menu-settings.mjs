import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import fs from 'node:fs';
import path from 'node:path';
const dir = path.resolve(import.meta.dirname, '..');
const dom = new JSDOM(fs.readFileSync(path.join(dir, 'index.html'), 'utf8'), { url: 'http://localhost/', pretendToBeVisual: true, runScripts: 'outside-only' });
const { window } = dom;
globalThis.window = window; globalThis.document = window.document;
Object.defineProperty(globalThis, 'navigator', { value: window.navigator, configurable: true });
globalThis.localStorage = window.localStorage; globalThis.sessionStorage = window.sessionStorage;
globalThis.HTMLElement = window.HTMLElement;
globalThis.requestAnimationFrame = window.requestAnimationFrame = () => 0;
window.confirm = () => true;
new Function(fs.readFileSync(path.join(dir, 'tests/.harness-bundle.js'), 'utf8'))();
document.dispatchEvent(new window.Event('DOMContentLoaded', { bubbles: true }));
const click = id => document.getElementById(id).click();
click('btn-settings');
assert.ok(!document.getElementById('settings-screen').classList.contains('hidden'));
const quality = document.getElementById('setting-quality'); quality.value = 'low'; quality.dispatchEvent(new window.Event('change'));
const lang = document.getElementById('setting-language'); lang.value = 'en'; lang.dispatchEvent(new window.Event('change'));
assert.equal(JSON.parse(localStorage.getItem('lastshore.settings.v1')).quality, 'low');
assert.equal(document.getElementById('btn-start').textContent, 'New game');
lang.value = 'ru'; lang.dispatchEvent(new window.Event('change'));
assert.equal(document.getElementById('btn-start').textContent, 'Новая игра');
click('btn-settings-close');
click('btn-rooms');
document.getElementById('server-url').value = 'https://example.org/'; click('btn-server-add');
assert.deepEqual(JSON.parse(localStorage.getItem('lastshore.servers.v1')), ['https://example.org/']);
click('btn-server-remove'); assert.deepEqual(JSON.parse(localStorage.getItem('lastshore.servers.v1')), []);
click('btn-start'); await new Promise(r => setTimeout(r, 250));
const game = window.__game; assert.ok(game?.running); assert.equal(game.quality, 2);
game.update(0.01); assert.equal(game.scene.fog.near, 1400);
game.state.health = 73; game.state.inventory.wood = 11;
game.boat.x = 35; game.boat.z = 45; game.boat.heading = 0.8;
const node = game.resources.nodes.find(n => n.type === 'tree');
game.resources.strike(node, { chop: 10000 }); assert.equal(node.alive, false);
game.world.removePickup(game.world.pickups[0]); const pickups = game.world.pickups.length;
game.pause(); click('btn-pause-saves');
let row = document.querySelector('.save-slot'); row.querySelector('button').click();
const data = JSON.parse(localStorage.getItem('lastshore.slot.1.v1'));
assert.equal(data.need[0], 73); assert.equal(data.inv.wood, 11); assert.equal(data.boat.x, 35);
game.state.health = 10; game.running = false;
node.alive = true; game.world.addPickup('wood', 0, 0);
row = document.querySelector('.save-slot'); row.querySelectorAll('button')[1].click();
await new Promise(r => setTimeout(r, 250));
assert.equal(game.state.health, 73); assert.equal(game.state.inventory.wood, 11); assert.equal(game.boat.x, 35);
assert.equal(node.alive, false); assert.equal(game.world.pickups.length, pickups);
console.log('MENU, SETTINGS AND SAVES OK'); process.exit(0);
