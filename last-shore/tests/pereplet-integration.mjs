import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import fs from 'node:fs';
import path from 'node:path';
const dir=path.resolve(import.meta.dirname,'..');
const dom=new JSDOM(fs.readFileSync(path.join(dir,'index.html'),'utf8'),{url:'http://localhost/',pretendToBeVisual:true,runScripts:'outside-only'});
globalThis.window=dom.window; globalThis.document=dom.window.document;
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
globalThis.localStorage=dom.window.localStorage; globalThis.sessionStorage=dom.window.sessionStorage;
globalThis.HTMLElement=dom.window.HTMLElement;
globalThis.requestAnimationFrame=dom.window.requestAnimationFrame=()=>0;
new Function(fs.readFileSync(path.join(dir,'tests/.harness-bundle.js'),'utf8'))();
document.dispatchEvent(new window.Event('DOMContentLoaded',{bubbles:true}));
document.getElementById('btn-start').click(); await new Promise(r=>setTimeout(r,300));
const game=window.__game; assert.ok(game?.running);
const resources=game.resources; const player=game.player.position;
const fire=resources.addCampfire(player.x+3,player.z+3);
const fire2=resources.addCampfire(player.x+5,player.z+5); fire2.fuel=.02;
for(let i=0;i<60;i++) resources.update(1/60);
assert.equal(resources.perepletClock.tick,30);
assert.ok(Math.abs(fire.fuel-59)<1e-9); assert.equal(fire2.fuel,0); assert.equal(fire2.flame.visible,false);
resources.addFuel(fire2,5); resources.update(1/30);
assert.ok(fire2.fuel>4.96 && fire2.fuel<5); assert.equal(fire2.flame.visible,true);
assert.ok(game.save()); const saved=JSON.parse(localStorage.getItem('lastshore.save.v1'));
assert.ok(saved.campfires.some(f=>f.fuel===59));
const node=resources.nodes.find(n=>n.type==='rock');
resources.strike(node,{mine:100}); assert.equal(node.alive,false);
node.respawnAt=resources.time+0.1;
resources.update(.1); assert.equal(node.alive,true); assert.equal(node.hp,node.maxHp);
const before=fire.fuel; resources.update(.5);
assert.equal(resources.perepletClock.tick,38);
assert.ok(resources.perepletClock.accumulator>.3);
while(resources.perepletClock.accumulator + 1e-9 >= resources.perepletClock.step) resources.update(0);
assert.ok(Math.abs((before-fire.fuel)-.5)<1e-9);
const ticking=resources.perepletClock.tick;
game.pause(); game.frame(); assert.equal(resources.perepletClock.tick,ticking);
assert.ok(resources.removeCampfire(fire2)); resources.update(1/30);
assert.equal(resources.campfires.includes(fire2),false);
console.log('ПЕРЕПЛЁТ В ИГРЕ: КОСТРЫ, РЕСУРСЫ, ПАУЗА И СОХРАНЕНИЕ OK'); process.exit(0);
