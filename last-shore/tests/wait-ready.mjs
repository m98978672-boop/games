/* Ожидание готовности игры вместо фиксированной паузы.

   Было: `await new Promise(r => setTimeout(r, 300))` во всех тестах. На
   рабочей машине мир собирается за ~1200 мс, то есть тест стартовал
   раньше, чем игра была готова. Локально это проходило только потому,
   что сборка уже была прогрета кешем; на холодной машине CI в 300 мс не
   укладывалось ничего, и проверки бежали по недособранному миру —
   отсюда «звери застревают», «дома зверей не построены» и прочее, чего
   на месте не воспроизвести.

   Теперь ждём события, а не время: window.__game появляется ровно тогда,
   когда мир собран и игра готова к проверкам. */
export async function waitReady(window, timeout = 60000) {
  const started = Date.now();
  while (!window.__game) {
    if (Date.now() - started > timeout) {
      throw new Error(`игра не собралась за ${Math.round(timeout / 1000)} с`);
    }
    await new Promise((r) => setTimeout(r, 25));
  }
  return window.__game;
}
