export const CATEGORIES = BLOCKS.map((b) => ({
  base: b.base, key: b.key, title: b.title, aspects: b.aspects,
}));

/* Слоты аудита: аспект × типичный дефект, по порядку. */
function auditSlots(block) {
  const out = [];
  for (const aspect of block.aspects) {
    for (const state of STATES) out.push(aspect + ' — ' + state);
  }
  return out;
}

export const CODES = [];
for (const b of BLOCKS) {
  const named = new Map();
  for (const [off, title, rule, severity] of b.checks) {
    named.set(off, { code: b.base + off, block: b.key, category: b.title, title, rule, severity });
  }
  const slots = auditSlots(b);
  let k = 0;
  for (let off = 0; off <= 99; off++) {
    const hit = named.get(off);
    if (hit) { hit.named = true; hit.audit = false; CODES.push(hit); continue; }
    CODES.push({
      code: b.base + off, block: b.key, category: b.title,
      title: slots[k++] || 'аудит подсистемы',
      rule: null, severity: null, named: false, audit: true,
    });
  }
}

if (CODES.length !== 1000 || CODES.some((c) => !c)) {
  throw new Error('каталог кодов собран неверно: ' + CODES.length);
}

/* Код по имени правила: детектор возвращает находку с rule, а в отчёте
   показывается код — так ищут по номеру. */
export const CODE_BY_RULE = new Map();
for (const c of CODES) if (c.rule && !CODE_BY_RULE.has(c.rule)) CODE_BY_RULE.set(c.rule, c.code);

export const codeOf = (code) => String(code).padStart(3, '0');
export const blockOf = (code) => BLOCKS.find((b) => code >= b.base && code <= b.base + 99);

/* Таблица для документации и флага --codes. */
export function codeTable(filter) {
  const rows = CODES.filter((c) => filter == null || (c.code >= filter[0] && c.code <= filter[1]));
  return rows.map((c) => ({ code: codeOf(c.code), category: c.category, title: c.title, live: !!c.rule }));
}
