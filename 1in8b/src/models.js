  var BY_ID = {};
  MODELS.forEach(function (m) { BY_ID[m.id] = m; });

  var GROUPS = [];
  MODELS.forEach(function (m) { if (GROUPS.indexOf(m.group) < 0) GROUPS.push(m.group); });

  function byGroup(group) {
    return MODELS.filter(function (m) { return m.group === group; });
  }

  function colorOf(key, o) {
    var c = PAL[key] || '#888888';
    if (o) {
      if (o.tint) c = mix(c, o.tint, o.tintK === undefined ? 0.35 : o.tintK);
      if (o.dark) c = shade(c, -o.dark);
      if (o.light) c = shade(c, o.light);
    }
    return c;
  }

  /* Нарисовать модельку: x — левый край, groundY — линия, на которой
     она стоит, s — масштаб в пикселях на единицу. */
  function draw(id, g, x, groundY, s, o) {
    var m = BY_ID[id];
    if (!m) return false;
    o = o || {};
    s = s || 1;
    var top = groundY - m.h * s;
    for (var i = 0; i < m.parts.length; i++) {
      var p = m.parts[i];
      var pxX = o.flip ? x + (m.w - p.x - p.w) * s : x + p.x * s;
      var w = Math.max(1, Math.round(p.w * s));
      var h = Math.max(1, Math.round(p.h * s));
      g.fillStyle = colorOf(p.c, o);
      g.fillRect(Math.round(pxX), Math.round(top + p.y * s), w, h);
    }
    return true;
  }

  /* Устойчивый выбор: одно зерно — одна и та же вещь в сцене. */
  function pick(group, seed) {
    var pool = byGroup(group);
    if (!pool.length) pool = MODELS;
    return pool[Math.abs(Math.floor(seed || 0)) % pool.length];
  }

  function sizeOf(id) {
    var m = BY_ID[id];
    return m ? { w: m.w, h: m.h } : { w: 0, h: 0 };
  }

